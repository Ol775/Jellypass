// Dependency-free PNG rasteriser. 88px artwork displays at 44px in email.
import { deflateSync } from 'node:zlib';
import { writeFileSync } from 'node:fs';
const size = 88, samples = 4;
// Ticket follows docs/mockups/names-jelly.html #tk, centred at 2x scale.
const points = [[5,9],[27,9],[27,13.5]];
for(let i=1;i<=64;i++){const a=-Math.PI/2-i*Math.PI/64;points.push([27+2.5*Math.cos(a),16+2.5*Math.sin(a)]);}
points.push([27,23],[5,23],[5,18.5]);
for(let i=1;i<=64;i++){const a=Math.PI/2-i*Math.PI/64;points.push([5+2.5*Math.cos(a),16+2.5*Math.sin(a)]);}
points.push([5,9]);
const path=points.map(([x,y])=>[12+2*x,12+2*y]);
function distance(x,y,a,b){const dx=b[0]-a[0],dy=b[1]-a[1],t=Math.max(0,Math.min(1,((x-a[0])*dx+(y-a[1])*dy)/(dx*dx+dy*dy)));return Math.hypot(x-a[0]-t*dx,y-a[1]-t*dy);}
function pixel(x,y){
 const dx=Math.max(20-x,0,x-68),dy=Math.max(20-y,0,y-68);
 if(dx*dx+dy*dy>400)return [0,0,0,0];
 const stroke=path.slice(1).some((p,i)=>distance(x,y,path[i],p)<=1.2);
 const tx=(x-12)/2,ty=(y-12)/2;
 const triangle=tx>=14&&tx<=19.5&&Math.abs(ty-16)<=(19.5-tx)*3.2/5.5;
 return stroke||triangle?[255,255,255,255]:[15,118,110,255];
}
const raw=Buffer.alloc(size*(1+size*4));
for(let y=0;y<size;y++)for(let x=0;x<size;x++){
 const sums=[0,0,0,0];
 for(let sy=0;sy<samples;sy++)for(let sx=0;sx<samples;sx++){const p=pixel(x+(sx+.5)/samples,y+(sy+.5)/samples);for(let c=0;c<4;c++)sums[c]+=p[c];}
 const offset=y*(1+size*4)+1+x*4;
 for(let c=0;c<3;c++)raw[offset+c]=sums[3]?Math.round(sums[c]*255/sums[3]):0;
 raw[offset+3]=Math.round(sums[3]/(samples*samples));
}
function crc32(data){let crc=0xffffffff;for(const byte of data){crc^=byte;for(let i=0;i<8;i++)crc=(crc>>>1)^((crc&1)?0xedb88320:0);}return (crc^0xffffffff)>>>0;}
function chunk(type,data){const name=Buffer.from(type),len=Buffer.alloc(4),crc=Buffer.alloc(4);len.writeUInt32BE(data.length);crc.writeUInt32BE(crc32(Buffer.concat([name,data])));return Buffer.concat([len,name,data,crc]);}
const ihdr=Buffer.alloc(13);ihdr.writeUInt32BE(size,0);ihdr.writeUInt32BE(size,4);ihdr[8]=8;ihdr[9]=6;
const png=Buffer.concat([Buffer.from('89504e470d0a1a0a','hex'),chunk('IHDR',ihdr),chunk('IDAT',deflateSync(raw)),chunk('IEND',Buffer.alloc(0))]);
writeFileSync(new URL('../src/emails/logo.ts',import.meta.url),'// Generated by scripts/make-email-logo.mjs; 88×88 PNG displayed at 44×44.\nexport const LOGO_PNG_BASE64 = '+JSON.stringify(png.toString('base64'))+';\n');
