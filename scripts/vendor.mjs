// Run after installing maplibre-gl, pmtiles and qrcode-generator. Generated modules ship with the Worker.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
await mkdir(new URL('../src/views/vendor/',import.meta.url),{recursive:true});
for(const [name,path] of [['maplibre','maplibre-gl/dist/maplibre-gl.js'],['maplibre-css','maplibre-gl/dist/maplibre-gl.css'],['pmtiles','pmtiles/dist/pmtiles.js'],['qrcode','qrcode-generator/dist/qrcode.js']]) {
 const source=await readFile(new URL('../node_modules/'+path,import.meta.url),'utf8');
 await writeFile(new URL('../src/views/vendor/'+name+'.ts',import.meta.url),'// Generated by scripts/vendor.mjs; do not edit.\nexport default '+JSON.stringify(source)+';\n');
}
await writeFile(new URL('../src/views/vendor/assets.ts',import.meta.url), `// Generated by scripts/vendor.mjs; do not edit.
import maplibre from './maplibre';
import css from './maplibre-css';
import pmtiles from './pmtiles';
import qrcode from './qrcode';
export const vendorAssets: Record<string,string> = {'maplibre.js':maplibre,'maplibre.css':css,'pmtiles.js':pmtiles,'qrcode.js':qrcode};
`);
